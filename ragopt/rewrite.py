"""Query rewriting: synonym expansion and HyDE.

Rewriting attacks vocabulary mismatch — the query says "cost" while the
docs say "price". Both techniques are deterministic here; in production
the HyDE hypothetical document would be generated by an LLM.
"""

import re

# Small built-in synonym map (bidirectional lookup at rewrite time).
_SYNONYMS = {
    "cost": ["price", "charge", "fee"],
    "price": ["cost", "charge"],
    "fast": ["speed", "quick", "top speed"],
    "speed": ["fast", "velocity"],
    "long": ["duration", "period"],
    "buy": ["purchase", "order"],
    "purchase": ["buy", "order"],
    "fix": ["repair", "troubleshoot"],
    "repair": ["fix"],
    "send": ["ship", "deliver"],
    "ship": ["send", "deliver"],
    "how": ["what is the way", "steps"],
    "warranty": ["guarantee", "coverage"],
    "guarantee": ["warranty", "coverage"],
}


class QueryRewriter:
    """Expands the query with synonyms from a small built-in map."""

    name = "rewrite"

    def __init__(self, synonyms: dict = None):
        self.synonyms = synonyms or _SYNONYMS

    def rewrite(self, query: str) -> str:
        words = re.findall(r"[a-zA-Z0-9]+", query)
        extra = []
        for w in words:
            for syn in self.synonyms.get(w.lower(), []):
                if syn.lower() not in query.lower():
                    extra.append(syn)
        if extra:
            return query + " " + " ".join(extra)
        return query


class HyDE:
    """Hypothetical Document Embeddings (deterministic simulation).

    Real HyDE asks an LLM to write a hypothetical answer, then embeds it.
    Here we build the hypothetical document from a deterministic template
    over the query's key terms, then embed with the provided model.
    """

    name = "hyde"

    def __init__(self, embeddings):
        self.embeddings = embeddings

    def hypothetical_doc(self, query: str) -> str:
        terms = re.findall(r"[a-zA-Z0-9]+", query.lower())
        # Drop stopwords for a cleaner hypothetical answer.
        stop = {"what", "how", "does", "do", "is", "are", "the", "a", "an",
                "of", "for", "to", "in", "on", "it", "and", "or", "i", "you"}
        keywords = [t for t in terms if t not in stop]
        core = " ".join(keywords) if keywords else query
        return (
            f"The answer regarding {core} is as follows. "
            f"Acme Robotics documents state the relevant specification: {core}. "
            f"For details on {core}, refer to the official product documentation."
        )

    def embed(self, query: str) -> list:
        return self.embeddings.embed(self.hypothetical_doc(query))
